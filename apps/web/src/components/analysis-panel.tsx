"use client";

import { useCallback, useEffect, useState } from "react";
import type { AnalysisStateDto, IncidentDto } from "@platform/shared";
import { ApiError } from "../lib/api-client";
import { SEVERITY_LABEL, errorText } from "../lib/format";
import { api } from "../lib/session";
import { useCan } from "./shell";

const POLL_MS = 2500;

/**
 * AI-suggested triage. Hidden entirely when the server has no AI provider. The suggestion is advisory: nothing is
 * applied unless a responder clicks, and that goes through the normal audited, version-checked update.
 */
export function AnalysisPanel({ incident, onApplySeverity }: { incident: IncidentDto; onApplySeverity(severity: IncidentDto["severity"]): Promise<void> }) {
  const canRequest = useCan("analysis:request");
  const canUpdate = useCan("incident:update");
  const [state, setState] = useState<AnalysisStateDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    try {
      setState(await api.analysisState(incident.id));
    } catch (e) {
      setError(errorText(e));
    }
  }, [incident.id]);

  useEffect(() => {
    void load();
  }, [load]);

  // Poll only while work is pending (queued or running); stop as soon as it finishes.
  const status = state?.analysis?.status;
  useEffect(() => {
    if (status !== "queued" && status !== "running") return;
    const timer = setInterval(() => void load(), POLL_MS);
    return () => clearInterval(timer);
  }, [status, load]);

  if (!state?.enabled) return null;
  const a = state.analysis;

  async function rerun() {
    setBusy(true);
    setError(null);
    try {
      setState(await api.requestAnalysis(incident.id));
    } catch (e) {
      setError(e instanceof ApiError && e.status === 409 ? "An analysis is already running." : errorText(e));
      await load();
    }
    setBusy(false);
  }

  return (
    <section aria-labelledby="ai-h" className="card">
      <h2 id="ai-h" style={{ marginTop: 0 }}>
        AI analysis <span className="badge">Suggestion</span>
      </h2>
      <div role="alert" className="form-error">
        {error}
      </div>
      {!a ? <p className="muted">No analysis yet.</p> : null}
      {a && (a.status === "queued" || a.status === "running") ? (
        <p role="status">{a.status === "queued" ? "Queued for analysis…" : "Analysing…"}</p>
      ) : null}
      {a?.status === "failed" ? (
        <p role="status">
          The analysis could not be completed ({a.errorCode?.replace("_", " ")}). You can try again; nothing else is affected.
        </p>
      ) : null}
      {a?.status === "completed" ? (
        <div data-testid="analysis-result">
          <p className="prewrap">{a.summary}</p>
          <dl>
            <dt>Suggested severity</dt>
            <dd>
              {a.suggestedSeverity ? SEVERITY_LABEL[a.suggestedSeverity] : "—"}
              {canUpdate && a.suggestedSeverity && a.suggestedSeverity !== incident.severity ? (
                <>
                  {" "}
                  <button type="button" className="btn secondary" onClick={() => void onApplySeverity(a.suggestedSeverity as IncidentDto["severity"])}>
                    Apply {a.suggestedSeverity.toUpperCase()}
                  </button>
                </>
              ) : null}
            </dd>
            <dt>Category</dt>
            <dd>{a.category}</dd>
            <dt>Probable cause</dt>
            <dd className="prewrap">{a.probableCause}</dd>
            <dt>Suggested steps</dt>
            <dd>
              <ol>
                {(a.steps ?? []).map((step, i) => (
                  <li key={i} className="prewrap">
                    {step}
                  </li>
                ))}
              </ol>
            </dd>
          </dl>
          {a.incidentVersion < incident.version ? (
            <p className="muted">This analysis was made before the latest changes to the incident. Re-run it to refresh.</p>
          ) : null}
          <p className="muted">Generated by an AI model ({a.model}). It can be wrong: verify before acting.</p>
        </div>
      ) : null}
      {canRequest && a?.status !== "queued" && a?.status !== "running" ? (
        <button type="button" className="btn secondary" disabled={busy} onClick={() => void rerun()}>
          {a ? "Re-run analysis" : "Analyse"}
        </button>
      ) : null}
    </section>
  );
}
